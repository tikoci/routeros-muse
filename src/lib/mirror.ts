// devices.toml (D53, T148): a generated, read-only text mirror of the
// workspace device.cdb, so grep and file-reading agents find hosts,
// users and service ports without a centrs call. The CDB stays the
// source of truth; this file is rewritten from it and never read back.
// Only MirrorRow fields reach it (no passwords, keys or secrets).
import * as nodeFs from "node:fs";
import * as path from "node:path";
import type { MirrorRow } from "./fleet";
import { PORT_KEYS } from "./fleet";
import { writeWorkspaceFile } from "./workspace";

export const MIRROR_FILE = "devices.toml";

/** First line of every generated file: the ownership marker. */
export const MIRROR_MARKER =
	"# devices.toml — GENERATED by routeros-muse from device.cdb. Do not edit.";

const HEADER = [
	MIRROR_MARKER,
	"# Rewritten whenever the device list is read (the UI, Add device,",
	"# Access, Remove). Change devices in the CDB instead: the UI, or",
	"# `centrs devices add|set|remove`. No passwords or keys are written.",
	"# id is the CDB target: the address centrs connects to. Per-device",
	"# intent (site, role, expected state) lives in router.toml or",
	'# inventory/, linked by cdb = "<id>".',
];

/** TOML basic string (JSON escapes are a valid subset here). */
function str(v: string): string {
	return JSON.stringify(v);
}

export function renderDevicesToml(rows: MirrorRow[]): string {
	const lines = [...HEADER, ""];
	if (rows.length === 0) lines.push("# (no devices in the CDB yet)", "");
	const sorted = [...rows].sort((a, b) => a.id.localeCompare(b.id));
	for (const r of sorted) {
		lines.push("[[device]]", `id = ${str(r.id)}`);
		if (r.user) lines.push(`user = ${str(r.user)}`);
		for (const key of PORT_KEYS) {
			const v = r.ports[key];
			if (v === undefined) continue;
			lines.push(`${key} = ${/^\d+$/.test(v) ? v : str(v)}`);
		}
		if (r.webfigUrl) lines.push(`webfig = ${str(r.webfigUrl)}`);
		lines.push("");
	}
	return lines.join("\n");
}

export type MirrorWrite =
	| { written: boolean }
	| { written: false; why: string };

/**
 * Write the mirror into the workspace root. Never overwrites a
 * devices.toml the owner or agent wrote (no marker on line 1), skips
 * an unchanged file, and goes through writeWorkspaceFile (T98: no
 * symlink follow, TOML validated).
 */
export function writeDevicesMirror(
	root: string,
	rows: MirrorRow[],
): MirrorWrite {
	const text = renderDevicesToml(rows);
	const full = path.join(root, MIRROR_FILE);
	let current: string | null = null;
	try {
		const st = nodeFs.lstatSync(full);
		if (!st.isFile())
			return { written: false, why: `${MIRROR_FILE} is not a regular file` };
		current = nodeFs.readFileSync(full, "utf8");
	} catch {
		current = null;
	}
	if (current !== null) {
		if (current.split("\n", 1)[0] !== MIRROR_MARKER)
			return {
				written: false,
				why: `${MIRROR_FILE} exists without the generated marker; left alone`,
			};
		if (current === text) return { written: false };
	}
	const res = writeWorkspaceFile(root, MIRROR_FILE, text);
	if (res.status !== 200) {
		const why = (res.body as { why?: string }).why ?? `status ${res.status}`;
		return { written: false, why };
	}
	return { written: true };
}
